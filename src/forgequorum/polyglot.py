def specialist(name: str, domain: str, stack: str, focus: tuple[str, ...], *, readonly: bool = False) -> Agent:
    """Keep each role specific and enforce evidence-driven, stack-native work."""
    return Agent(
        name=name,
        description=f'{domain}: {stack}. Use native conventions and verify with project tools.',
        mission=f'Own {domain.lower()} decisions and implementation in an existing {stack} codebase without inventing tool results.',
        focus=(
            f'Inspect actual {stack} versions, lockfiles, project conventions and compatible APIs before choosing code or commands.',
            *focus,
            'Use repository-native formatters, static checks and tests when available; report missing tools or unrun checks.',
            'Respect existing ownership boundaries; do not introduce unrelated frameworks or destructive migrations.',
        ),
        output='Scoped implementation or findings, impacted files, reproducible checks, compatibility notes and remaining risks.',
        readonly=readonly,
    )


